// One-off for phasing out the Google Sheet: builds supabase/import-characters.sql from the Members tab of the sheet and checks the result.
//   node tools/import-characters.mjs           writes the SQL and prints what needs a look
//   node tools/import-characters.mjs --check   after running that SQL: compares the table characters with the sheet
// Only public data is read (the sheet, and Supabase with the public key). Run it again just before the switch: the SQL refreshes rows that
// were only imported so far and never touches a row someone changed on the site. Node 20+, no dependencies.
import { readFileSync, writeFileSync } from 'node:fs';

const OUT = 'supabase/import-characters.sql';
const setting = (key) => readFileSync('js/config.js', 'utf8').match(new RegExp(`${key}\\s*=\\s*'([^']*)'`))[1];
const URL_ = setting('SUPABASE_URL');
const KEY = setting('SUPABASE_ANON_KEY');
const norm = (s) => String(s ?? '').trim().toLowerCase();
const squash = (s) => norm(s).replace(/\s+/g, '');
const q = (v) => (v === null || v === undefined || v === '' ? 'null' : `'${String(v).replace(/'/g, "''")}'`);

function parseCsv(text) {
  const rows = []; let row = []; let field = ''; let inside = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inside) { if (c === '"' && text[i + 1] === '"') { field += '"'; i++; } else if (c === '"') inside = false; else field += c; }
    else if (c === '"') inside = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n') { row.push(field); rows.push(row); row = []; field = ''; }
    else if (c !== '\r') field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows;
}
async function rest(path) {
  const res = await fetch(`${URL_}/rest/v1/${path}`, { headers: { apikey: KEY } });
  if (!res.ok) throw new Error(`${path}: HTTP ${res.status} ${(await res.text()).slice(0, 150)}`);
  return res.json();
}
const num = (v) => (String(v ?? '').trim() === '' || Number.isNaN(Number(v)) ? null : Number(v));

// Same order of precedence as the site today: 1 active character = main; a main chosen on My profile wins from the Status in the sheet.
export function fromSheet(csvRows, choices) {
  const rows = csvRows.filter((r) => r[0]?.trim()).map((r) => {
    const professions = [];
    for (const [name, skill] of [[r[6], r[7]], [r[8], r[9]]]) if (name?.trim()) professions.push({ name: name.trim(), kind: 'primary', skill: num(skill) });
    for (const [name, skill] of [['Cooking', r[10]], ['First Aid', r[11]], ['Fishing', r[12]]]) if (num(skill) !== null) professions.push({ name, kind: 'secondary', skill: num(skill) });
    return { player: r[0].trim(), name: (r[1] ?? '').trim(), race: r[2]?.trim(), cls: r[3]?.trim(), role: r[4]?.trim(), level: num(r[5]), professions, recipes: r[13]?.trim(), updated: r[14]?.trim(), status: r[15]?.trim() || 'Main', notes: r[16]?.trim() };
  });
  const byPlayer = new Map();
  for (const r of rows) if (r.name && r.status !== 'Gestopt') byPlayer.set(norm(r.player), [...(byPlayer.get(norm(r.player)) ?? []), r]);
  const problems = [];
  for (const [player, list] of byPlayer) {
    const choice = choices.find((c) => norm(c.player_name) === player);
    const chosen = choice && list.find((r) => norm(r.name) === norm(choice.character_name));
    if (list.length === 1) list[0].status = 'Main';
    else if (chosen) list.forEach((r) => { r.status = r === chosen ? 'Main' : 'Alt'; });
    else if (list.filter((r) => r.status === 'Main').length !== 1) problems.push(`${list[0].player} has ${list.length} characters but not exactly one Main`);
  }
  const seen = new Set();
  for (const r of rows) if (r.name) { if (seen.has(norm(r.name))) problems.push(`"${r.name}" is in the sheet twice`); seen.add(norm(r.name)); }
  return { rows, problems };
}
const isoDay = (s) => { const m = /^(\d{1,2})-(\d{1,2})-(\d{4})$/.exec(s ?? ''); return m ? `${m[3]}-${m[2].padStart(2, '0')}-${m[1].padStart(2, '0')}` : null; };

export function toSql(rows, generatedOn) {
  const withName = rows.filter((r) => r.name).sort((a, b) => (a.status === 'Main') - (b.status === 'Main')); // alts first: a player's old main is an alt before the new main arrives
  const players = [...new Set(rows.map((r) => r.player))];
  const values = withName.map((r) => `  (${[q(r.player), q(r.name), q(r.race), q(r.cls), q(r.role), r.level ?? 'null', `${q(JSON.stringify(r.professions))}::jsonb`, q(r.status), q(r.notes), q(r.recipes), isoDay(r.updated) ? `${q(isoDay(r.updated))}::timestamptz` : 'now()', q('sheet import')].join(', ')})`);
  return `-- Generated by tools/import-characters.mjs on ${generatedOn} from the Members tab of the guild sheet. Do not edit by hand: run the tool again.
-- Run it in the Supabase SQL Editor after supabase/schema.sql. Safe to run again: rows that someone changed on the site are left alone.
-- Players that are in the sheet but not in \`players\` are added: they then also appear under "Choose your player".
insert into public.players (player_name) values
${players.map((p) => `  (${q(p)})`).join(',\n')}
on conflict (player_name) do nothing;

insert into public.characters (player_name, name, race, class, role, level, professions, status, notes, recipes, updated_at, updated_by) values
${values.join(',\n')}
on conflict ((lower(btrim(name)))) do update set
  player_name = excluded.player_name, race = excluded.race, class = excluded.class, role = excluded.role, level = excluded.level, professions = excluded.professions,
  status = excluded.status, notes = excluded.notes, recipes = excluded.recipes, updated_at = excluded.updated_at, updated_by = excluded.updated_by
where public.characters.updated_by = 'sheet import';
`;
}

async function main() {
  const res = await fetch(`https://docs.google.com/spreadsheets/d/${setting('SHEET_ID')}/gviz/tq?tqx=out:csv&sheet=Members&range=A5:Q200&headers=0`);
  if (!res.ok) throw new Error(`Sheet: HTTP ${res.status}`);
  const { rows, problems } = fromSheet(parseCsv(await res.text()), await rest('main_characters?select=player_name,character_name'));
  const named = rows.filter((r) => r.name);

  if (process.argv.includes('--check')) {
    const table = await rest('characters?select=player_name,name,race,class,role,level,professions,status,notes,recipes,updated_by');
    const byName = new Map(table.map((t) => [norm(t.name), t]));
    const issues = [];
    const same = (a, b) => String(a ?? '').trim() === String(b ?? '').trim();
    for (const r of named) {
      const t = byName.get(norm(r.name));
      if (!t) { issues.push(`missing in the table: ${r.name}`); continue; }
      if (t.updated_by !== 'sheet import') continue; // changed on the site on purpose
      for (const [a, b, label] of [[t.player_name, r.player, 'player'], [t.race, r.race, 'race'], [t.class, r.cls, 'class'], [t.role, r.role, 'role'], [t.level, r.level, 'level'], [t.status, r.status, 'status'], [t.notes, r.notes, 'notes'], [t.recipes, r.recipes, 'recipes']]) if (!same(a, b)) issues.push(`${r.name}: ${label} is "${a ?? ''}" in the table, "${b ?? ''}" in the sheet`);
      if (JSON.stringify(t.professions) !== JSON.stringify(r.professions) && JSON.stringify([...t.professions].sort((x, y) => x.name.localeCompare(y.name)).map((p) => [p.name, p.kind, p.skill])) !== JSON.stringify([...r.professions].sort((x, y) => x.name.localeCompare(y.name)).map((p) => [p.name, p.kind, p.skill]))) issues.push(`${r.name}: professions differ`);
    }
    const inSheet = new Set(named.map((r) => norm(r.name)));
    for (const t of table) if (!inSheet.has(norm(t.name))) console.log(`Only in the table: ${t.name} (${t.player_name})`);
    console.log(`Table: ${table.length} characters. Sheet: ${named.length} with a name.`);
    console.log(issues.length ? `DIFFERENCES:\n- ${issues.join('\n- ')}` : 'No differences.');
    process.exitCode = issues.length ? 1 : 0;
    return;
  }

  // Characters on the site that the sheet does not have: they need a decision, the import does not guess.
  const [players, profiles, alts] = await Promise.all([rest('players?select=player_name'), rest('profiles?select=character_name,player_name'), rest('alts?select=character_name')]);
  const known = new Set(players.map((p) => norm(p.player_name)));
  const sheetNames = new Set(named.map((r) => norm(r.name)));
  const squashed = new Map(named.map((r) => [squash(r.name), r.name]));
  writeFileSync(OUT, toSql(rows, new Date().toISOString().slice(0, 10)));
  console.log(`Written ${OUT}: ${named.length} characters.`);
  for (const r of rows.filter((x) => !x.name)) console.log(`No character name, not imported: ${r.player} (${[r.race, r.cls, r.role].filter(Boolean).join(' ') || 'nothing filled in'}${r.notes ? `; note: ${r.notes}` : ''})`);
  for (const p of [...new Set(rows.map((r) => r.player))]) if (!known.has(norm(p))) console.log(`Not in players yet, will be added: ${p}`);
  for (const x of [...profiles, ...alts]) {
    if (!x.character_name || sheetNames.has(norm(x.character_name))) continue;
    const near = squashed.get(squash(x.character_name));
    console.log(near ? `On the site with another spelling, not imported: "${x.character_name}" (sheet: "${near}")` : `Only on the site, not imported: ${x.character_name}`);
  }
  for (const p of problems) console.log(`PROBLEM: ${p}`);
  if (problems.length) process.exitCode = 1;
}
if (process.argv[1]?.replace(/\\/g, '/').endsWith('tools/import-characters.mjs')) await main();
